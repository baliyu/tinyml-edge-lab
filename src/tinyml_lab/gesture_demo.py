"""The desk-gesture chain as it will run on the board, held to the Python chain on the PC.

firmware/sparkfun_edge/gesture_demo/ turns raw timestamped samples into a gesture number (resample to 50 Hz, window,
features, model). This module trains the model that goes into it, writes that model as C, builds the whole C chain with the
host compiler, and runs recordings through it sample by sample the way the board would receive them, so that its answers can
be compared with the Python chain (resample_to_grid, make_windows, feature_matrix, predict) window by window.

Nothing here runs on the board. A match proves the C code does what the Python code does; it says nothing about accuracy
on new sessions (that needs a held-out session, recorded after the model was trained).
"""
from __future__ import annotations

import ctypes
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

import numpy as np

from . import edge_gestures as eg
from .edge_features_c import C_DIR as FEATURES_DIR, N_FEATURES, compare_features, find_gcc
from .edge_gesture_eval import FOREST_TREES, TREE_DEPTH, ordered_labels
from .export_c import forest_to_c, tree_to_c

DEMO_DIR = Path(__file__).resolve().parents[2] / "firmware" / "sparkfun_edge" / "gesture_demo"
WRAP = 1 << 32
MODEL_KINDS = ("forest", "tree")


# ------------------------------------------------------------------------------------------------ the model, as C
def train_deployable(data_dir, model: str = "forest", feature_set: str = "raw", seed: int = 0):
    """Train one model on EVERY recording. Returns (clf, X, y, labels, dataset). It has no held-out score by construction."""
    from sklearn.ensemble import RandomForestClassifier
    from sklearn.tree import DecisionTreeClassifier

    if model not in MODEL_KINDS:
        raise ValueError(f"model must be one of {MODEL_KINDS}")
    ds = eg.load_dataset(data_dir)
    labels = ordered_labels(ds.y)
    X = eg.feature_matrix(ds.windows, ds.fs, feature_set)
    y = np.array([labels.index(v) for v in ds.y])
    if model == "forest":
        clf = RandomForestClassifier(n_estimators=FOREST_TREES, random_state=seed, n_jobs=-1)
    else:
        clf = DecisionTreeClassifier(max_depth=TREE_DEPTH, random_state=seed)
    return clf.fit(X, y), X, y, labels, ds


def model_sources(clf, labels, feature_set: str, model: str) -> tuple[str, str]:
    """(gesture_model.c, gesture_model.h) for a trained model. The C function takes the features of one window."""
    if model not in MODEL_KINDS:
        raise ValueError(f"model must be one of {MODEL_KINDS}")
    fname = f"gesture_model_{model}"
    body = forest_to_c(clf, fname) if model == "forest" else tree_to_c(clf, fname, thresholds="float")
    names = ", ".join(json.dumps(str(v)) for v in labels)
    h = "\n".join([
        "/* generated by tinyml_lab.gesture_demo; do not edit by hand */",
        "#ifndef GESTURE_MODEL_H", "#define GESTURE_MODEL_H", "",
        f"#define GESTURE_N_FEATURES {N_FEATURES[feature_set]}",
        f"#define GESTURE_USES_MOTION_FEATURES {1 if feature_set == 'motion' else 0}",
        f"#define GESTURE_N_CLASSES {len(labels)}", "",
        "extern const char *const GESTURE_CLASS_NAMES[GESTURE_N_CLASSES];",
        "/* The gesture number (an index into GESTURE_CLASS_NAMES) for one window's features, in the order of the model's JSON file. */",
        "int gesture_model_predict(const float *features);", "", "#endif", ""])
    c = "\n".join([
        "/* generated by tinyml_lab.gesture_demo; do not edit by hand */",
        '#include "gesture_model.h"', "", body.replace("/* generated by tinyml_lab.export_c; do not edit by hand */\n", ""), "",
        f"const char *const GESTURE_CLASS_NAMES[GESTURE_N_CLASSES] = {{{names}}};", "",
        f"int gesture_model_predict(const float *features) {{ return {fname}(features); }}", ""])
    return c, h


def write_model(clf, labels, feature_set: str, model: str, out_dir=DEMO_DIR, ds=None) -> dict:
    """Write gesture_model.c, gesture_model.h and gesture_model.json into out_dir. Returns the JSON content."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    c, h = model_sources(clf, labels, feature_set, model)
    (out_dir / "gesture_model.c").write_text(c, encoding="utf-8", newline="\n")
    (out_dir / "gesture_model.h").write_text(h, encoding="utf-8", newline="\n")
    size = ({"trees": int(len(clf.estimators_)), "nodes": int(sum(e.tree_.node_count for e in clf.estimators_))} if model == "forest"
            else {"nodes": int(clf.tree_.node_count)})
    meta = {"function": "int gesture_model_predict(const float *features)", "model": model, "feature_set": feature_set,
            "feature_names": eg.feature_names_for(feature_set), "classes": list(labels), "window_samples": eg.WINDOW,
            "fs_hz": eg.FS, "step_samples": eg.STEP, **size,
            "trained_on": ({"windows": int(len(ds.y)), "sessions": sorted(set(ds.session.tolist()))} if ds is not None else None),
            "note": "trained on every session, so it has no held-out score; the honest numbers are in results/gestures.json"}
    (out_dir / "gesture_model.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    return meta


def _stage(model_dir: Path, workdir: Path) -> Path:
    """A folder holding the chain's own two files and the model under test, nothing else. The compiler looks for a quoted #include next
    to the including file first, so building straight from the firmware folder would pick up whatever gesture_model.h is committed
    there instead of the model we mean to test."""
    for need in ("gesture_model.c", "gesture_model.h"):
        if not (model_dir / need).is_file():
            raise FileNotFoundError(f"{model_dir / need} is missing: write the model first (scripts/export_gesture_model.py)")
    stage = workdir / "stage"
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir(parents=True)
    for name in ("gesture_pipeline.c", "gesture_pipeline.h"):
        shutil.copy(DEMO_DIR / name, stage / name)
    for name in ("gesture_model.c", "gesture_model.h"):
        shutil.copy(model_dir / name, stage / name)
    return stage


# ------------------------------------------------------------------------------------------------ the chain, built for the PC
class CPipeline:
    """firmware/sparkfun_edge/gesture_demo/gesture_pipeline.c built with the host compiler and driven through ctypes."""

    def __init__(self, model_dir, real: str = "float", workdir=None, extra_flags=()):
        if real not in ("float", "double"):
            raise ValueError("real must be 'float' or 'double'")
        gcc = find_gcc()
        if gcc is None:
            raise RuntimeError("no C compiler found (install gcc)")
        model_dir = Path(model_dir)
        workdir = Path(workdir) if workdir else Path(tempfile.mkdtemp(prefix="gesture_pipeline_"))
        workdir.mkdir(parents=True, exist_ok=True)
        stage = _stage(model_dir, workdir)
        so = workdir / f"libgesture_pipeline_{real}.so"
        subprocess.run([gcc, "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror", "-pedantic", "-shared", "-fPIC", f"-DEF_REAL={real}", "-DGP_TEST_HOOKS", *extra_flags,
                        "-I", str(FEATURES_DIR), "-I", str(stage), str(stage / "gesture_pipeline.c"), str(FEATURES_DIR / "edge_features.c"),
                        str(stage / "gesture_model.c"), "-o", str(so), "-lm"], check=True, capture_output=True, text=True)
        lib = ctypes.CDLL(str(so))
        u32, i32 = ctypes.c_uint32, ctypes.c_int32
        lib.gp_state_size.restype = ctypes.c_size_t
        lib.gp_init.argtypes, lib.gp_init.restype = [ctypes.c_void_p, u32, u32], ctypes.c_int
        lib.gp_push.argtypes, lib.gp_push.restype = [ctypes.c_void_p, u32, i32, i32, i32], ctypes.c_int
        lib.gp_class.argtypes, lib.gp_class.restype = [ctypes.c_void_p], ctypes.c_int
        lib.gp_feature.argtypes, lib.gp_feature.restype = [ctypes.c_void_p, ctypes.c_int], ctypes.c_double
        for name in ("gp_windows", "gp_restarts", "gp_ignored"):
            getattr(lib, name).argtypes, getattr(lib, name).restype = [ctypes.c_void_p], u32
        self.lib, self.real = lib, real
        h = (stage / "gesture_model.h").read_text()
        self.n_features = int(h.split("GESTURE_N_FEATURES")[1].split()[0])

    def run(self, ticks, xyz, tick_hz: int, skip: int = 0) -> dict:
        """Feed samples one by one, as the board would. ticks: 32-bit counter values (already wrapped); xyz: (n, 3) integer milli-g."""
        lib = self.lib
        state = ctypes.create_string_buffer(int(lib.gp_state_size()))
        if lib.gp_init(state, int(tick_hz), int(skip)) != 0:
            raise ValueError("gp_init refused the tick rate")
        classes, feats = [], []
        xyz = np.asarray(xyz)
        for t, (x, y, z) in zip(np.asarray(ticks, dtype=np.uint64).tolist(), xyz.astype(np.int64).tolist()):
            if lib.gp_push(state, t, x, y, z):
                classes.append(int(lib.gp_class(state)))
                feats.append([lib.gp_feature(state, i) for i in range(self.n_features)])
        return {"classes": np.array(classes, dtype=int), "features": np.array(feats, dtype=np.float64).reshape(len(feats), self.n_features),
                "windows": int(lib.gp_windows(state)), "restarts": int(lib.gp_restarts(state)), "ignored": int(lib.gp_ignored(state))}


def ticks_from_seconds(t_s, tick_hz: int, start: int = 0) -> np.ndarray:
    """The 32-bit counter values for sample times in seconds (as the board would stamp them). start: the counter at t = 0."""
    return ((np.rint(np.asarray(t_s, dtype=np.float64) * tick_hz).astype(np.int64) + int(start)) % WRAP).astype(np.uint64)


# ------------------------------------------------------------------------------------------------ the Python reference
def python_chain(t_s, xyz, clf, feature_set: str, skip: int = 0, fs: float = eg.FS) -> dict:
    """What the Python code says for the same samples: resample, drop `skip` samples, cut windows, features, predict."""
    x = eg.resample_to_grid(t_s, xyz, fs)[skip:]
    w = eg.make_windows(x, eg.WINDOW, eg.STEP)
    if len(w) == 0:
        return {"classes": np.array([], dtype=int), "features": np.zeros((0, N_FEATURES[feature_set]))}
    X = eg.feature_matrix(w, fs, feature_set)
    return {"classes": clf.predict(X).astype(int), "features": X}


def compare_chains(c: dict, py: dict, feature_set: str) -> dict:
    """The C chain against the Python chain on the windows both produced (the C chain may run on past the Python one's last window)."""
    n = len(py["classes"])
    if len(c["classes"]) < n:
        raise AssertionError(f"the C chain produced {len(c['classes'])} windows, the Python chain {n}")
    cf = c["features"][:n]
    out = {"windows": n, "extra_c_windows": len(c["classes"]) - n,
           "class_mismatches": int(np.sum(c["classes"][:n] != py["classes"]))}
    out.update(compare_features(py["features"], cf, feature_set) if n else {"max_error_vs_feature_size": 0.0, "worst_feature": "", "windows_with_a_different_dominant_bin": 0})
    return out


def check_recordings(data_dir, clf, labels, feature_set: str, model_dir, real: str = "float", skip: int = None, workdir=None) -> dict:
    """Run every usable recording under data_dir through the C chain and compare with the Python chain. skip defaults to the
    number of samples the Python dataset trims at each end, so both chains cut windows from the same samples."""
    data_dir = Path(data_dir)
    ds = eg.load_dataset(data_dir)
    skip = int(round(eg.TRIM_S * eg.FS)) if skip is None else skip
    pipe = CPipeline(model_dir, real, workdir)
    per_file, totals = [], {"windows": 0, "class_mismatches": 0, "extra_c_windows": 0}
    worst, worst_name, dom = 0.0, "", 0
    for f in ds.files:
        path = next(data_dir.rglob(f["file"]))
        cap = eg.read_capture(path)
        tick_hz = int(cap.tick_hz or 3_000_000)
        ticks = ticks_from_seconds(cap.t_s, tick_hz)
        t_ref = ticks.astype(np.float64) / tick_hz     # the times the ticks stand for: a 32.768 kHz tick is coarser than the file's microseconds
        cout = pipe.run(ticks, np.rint(cap.xyz_mg).astype(np.int64), tick_hz, skip)
        pyout = python_chain(t_ref, np.rint(cap.xyz_mg), clf, feature_set, skip)
        # the dataset's own windows stop skip samples before the end; the Python chain here does not, so trim it the same way
        n_ref = f["windows"]
        pyout = {k: v[:n_ref] for k, v in pyout.items()}
        cmp = compare_chains(cout, pyout, feature_set)
        per_file.append({"file": f["file"], "label": f["label"], "session": f["session"], "tick_hz": tick_hz, **cmp})
        for k in totals:
            totals[k] += cmp[k]
        if cmp["max_error_vs_feature_size"] > worst:
            worst, worst_name = cmp["max_error_vs_feature_size"], f"{cmp['worst_feature']} in {f['file']}"
        dom += cmp["windows_with_a_different_dominant_bin"]
    return {"real": real, "files": len(per_file), **totals, "worst_feature_error": worst, "worst_feature": worst_name,
            "windows_with_a_different_dominant_bin": dom, "per_file": per_file}


# ------------------------------------------------------------------------------------------------ what the board build costs
ARM_FLAGS = ["-std=c11", "-mcpu=cortex-m4", "-mthumb", "-mfloat-abi=hard", "-mfpu=fpv4-sp-d16", "-Os", "-ffunction-sections", "-fdata-sections",
             "-fno-math-errno", "-fstack-usage", "-Wall", "-Wextra", "-Werror", "-pedantic"]


def arm_footprint(model_dir, workdir=None) -> dict | None:
    """Flash, stack and undefined symbols of the board build (Cortex-M4F, -Os, as the Apollo3 runs), or None without an ARM compiler.
    Nothing is run: these are sizes from the compiler. The stack figure adds the frames along the deepest call path (an estimate)."""
    cc = shutil.which("arm-none-eabi-gcc")
    if cc is None:
        return None
    model_dir = Path(model_dir)
    work = Path(workdir) if workdir else Path(tempfile.mkdtemp(prefix="gesture_arm_"))
    work.mkdir(parents=True, exist_ok=True)
    stage = _stage(model_dir, work)
    (work / "probe.c").write_text('#include "gesture_pipeline.h"\nchar gp_state_probe[sizeof(gp_state)];\n')
    parts = {"pipeline": stage / "gesture_pipeline.c", "features": FEATURES_DIR / "edge_features.c", "model": stage / "gesture_model.c", "probe": work / "probe.c"}
    inc = ["-I", str(FEATURES_DIR), "-I", str(stage)]
    flash, stack, objs = {}, {}, []
    for name, src in parts.items():
        obj = work / f"{name}.o"
        subprocess.run([cc, *ARM_FLAGS, *inc, "-c", str(src), "-o", str(obj)], check=True, capture_output=True, text=True)
        row = subprocess.run(["arm-none-eabi-size", str(obj)], check=True, capture_output=True, text=True).stdout.splitlines()[1].split()
        text, data, bss = int(row[0]), int(row[1]), int(row[2])
        if name == "probe":
            state_bytes = bss
            continue
        flash[name] = text + data
        objs.append(obj)
        for line in (work / f"{name}.su").read_text().splitlines():
            head, nbytes = line.split("\t")[:2]
            stack[head.split(":")[-1]] = int(nbytes)
    undefined = sorted({ln.split()[-1] for o in objs for ln in subprocess.run(["arm-none-eabi-nm", "-u", str(o)], check=True, capture_output=True,
                                                                            text=True).stdout.splitlines()})
    deepest = stack["gp_push"] + stack["gp_emit"] + max(stack["ef_raw_features" if "ef_raw_features" in stack else "ef_motion_features"]
                                                       + stack.get("channel_features", 0), stack.get("gesture_model_predict", 0) + 200)
    return {"compiler": subprocess.run([cc, "--version"], check=True, capture_output=True, text=True).stdout.splitlines()[0],
            "flash_bytes": {**flash, "total": sum(flash.values())}, "state_ram_bytes": state_bytes, "stack_bytes": stack,
            "deepest_stack_estimate_bytes": int(deepest), "undefined_symbols": undefined}
