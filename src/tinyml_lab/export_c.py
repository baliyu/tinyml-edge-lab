"""Export a scikit-learn decision tree as a dependency-free C function.

Thresholds are written as doubles and compared as (double)x[i] <= threshold, which is
exactly how scikit-learn compares (float32 input against a float64 threshold), so the C
function returns the same class as clf.predict. A float-threshold variant is deliberately
not offered: rounding a threshold to float32 can flip a split.
"""
import numpy as np


def tree_to_c(clf, func_name="tree_predict"):
    t = clf.tree_
    classes = clf.classes_
    lines = ["/* generated by tinyml_lab.export_c; do not edit by hand */",
             f"int {func_name}(const float *x)", "{"]

    def rec(node, depth):
        ind = "    " * (depth + 1)
        if t.children_left[node] == -1:
            label = int(classes[int(np.argmax(t.value[node][0]))])
            lines.append(f"{ind}return {label};")
            return
        thr = repr(float(t.threshold[node]))
        lines.append(f"{ind}if ((double)x[{int(t.feature[node])}] <= {thr}) {{")
        rec(int(t.children_left[node]), depth + 1)
        lines.append(f"{ind}}} else {{")
        rec(int(t.children_right[node]), depth + 1)
        lines.append(f"{ind}}}")

    rec(0, 0)
    lines.append("}")
    return "\n".join(lines) + "\n"
