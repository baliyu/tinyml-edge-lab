"""Export scikit-learn trees and forests as dependency-free C.

Thresholds
----------
scikit-learn compares a float32 input against a float64 threshold. Two exact encodings are offered:

* ``thresholds="double"``: the threshold as a double, compared as ``(double)x[i] <= t``. Exact, but a Cortex-M4F's FPU is
  single-precision only, so this runs in software and stores 8 bytes per threshold.
* ``thresholds="float"``: the threshold rounded DOWN to the largest float32 not above it. For any float32 ``x``,
  ``x <= t`` and ``x <= floor32(t)`` are the same test, so this is exact too, with 4-byte constants and an FPU compare.
  Rounding to the NEAREST float32 instead would flip a split when the midpoint of two adjacent floats rounds up.

Forests
-------
``forest_to_c`` reproduces scikit-learn's soft vote: the leaf class probabilities (float32) are summed over the trees and the
first largest class wins. Sums are float32, so a near-tie can in principle differ from scikit-learn's float64 sum; measure the
agreement on your data (``footprint.host_agreement``).
"""
import numpy as np


def floor_f32(value):
    """Largest float32 that is not greater than `value`."""
    t = np.float32(value)
    if float(t) > value:
        t = np.nextafter(t, np.float32(-np.inf))
    return t


def f32_literal(t):
    """A C float literal that parses back to exactly the float32 `t`."""
    s = format(float(t), ".9g")
    if not any(ch in s for ch in ".en"):
        s += ".0"
    return s + "f"


def tree_to_c(clf, func_name="tree_predict", thresholds="double"):
    if thresholds not in ("double", "float"):
        raise ValueError("thresholds must be 'double' or 'float'")
    t = clf.tree_
    classes = clf.classes_
    lines = ["/* generated by tinyml_lab.export_c; do not edit by hand */",
             f"int {func_name}(const float *x)", "{"]

    def rec(node, depth):
        ind = "    " * (depth + 1)
        if t.children_left[node] == -1:
            label = int(classes[int(np.argmax(t.value[node][0]))])
            lines.append(f"{ind}return {label};")
            return
        thr = float(t.threshold[node])
        if thresholds == "double":
            cond = f"(double)x[{int(t.feature[node])}] <= {thr!r}"
        else:
            cond = f"x[{int(t.feature[node])}] <= {f32_literal(floor_f32(thr))}"
        lines.append(f"{ind}if ({cond}) {{")
        rec(int(t.children_left[node]), depth + 1)
        lines.append(f"{ind}}} else {{")
        rec(int(t.children_right[node]), depth + 1)
        lines.append(f"{ind}}}")

    rec(0, 0)
    lines.append("}")
    return "\n".join(lines) + "\n"


def forest_to_c(rf, func_name="forest_predict"):
    """Soft-voting random forest as C with float32 thresholds and a float32 leaf-probability table."""
    classes = [int(c) for c in rf.classes_]
    nc = len(classes)
    leaf_rows = []
    funcs = []
    for k, est in enumerate(rf.estimators_):
        t = est.tree_
        body = []

        def rec(node, depth):
            ind = "    " * (depth + 1)
            if t.children_left[node] == -1:
                v = t.value[node][0].astype(np.float64)
                probs = v / v.sum()
                body.append(f"{ind}return {len(leaf_rows)};")
                leaf_rows.append([f32_literal(np.float32(p)) for p in probs])
                return
            thr = f32_literal(floor_f32(float(t.threshold[node])))
            body.append(f"{ind}if (x[{int(t.feature[node])}] <= {thr}) {{")
            rec(int(t.children_left[node]), depth + 1)
            body.append(f"{ind}}} else {{")
            rec(int(t.children_right[node]), depth + 1)
            body.append(f"{ind}}}")

        rec(0, 0)
        funcs.append((k, body))
    n_leaves = len(leaf_rows)
    idtype = "uint16_t" if n_leaves < 65536 else "uint32_t"
    out = ["/* generated by tinyml_lab.export_c; do not edit by hand */", "#include <stdint.h>",
           f"#define FOREST_N_CLASSES {nc}", f"#define FOREST_N_LEAVES {n_leaves}",
           "static const float LEAF[FOREST_N_LEAVES][FOREST_N_CLASSES] = {"]
    out += ["    {" + ", ".join(r) + "}," for r in leaf_rows]
    out += ["};", "static const int CLASS_LABELS[FOREST_N_CLASSES] = {" + ", ".join(str(c) for c in classes) + "};"]
    for k, body in funcs:
        out.append(f"static {idtype} tree_{k}(const float *x)")
        out.append("{")
        out += body
        out.append("}")
    # the first tree assigns instead of adding to zero: the same numbers, and no memset call to zero the array
    out += [f"int {func_name}(const float *x)", "{", "    float acc[FOREST_N_CLASSES];",
            f"    {idtype} id;", "    int c;", "    int best = 0;"]
    for k, _ in funcs:
        op = "=" if k == 0 else "+="
        out.append(f"    id = tree_{k}(x); for (c = 0; c < FOREST_N_CLASSES; ++c) acc[c] {op} LEAF[id][c];")
    out += ["    for (c = 1; c < FOREST_N_CLASSES; ++c) if (acc[c] > acc[best]) best = c;",
            "    return CLASS_LABELS[best];", "}"]
    return "\n".join(out) + "\n"
